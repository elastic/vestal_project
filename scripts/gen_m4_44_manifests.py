#!/usr/bin/env python3
"""Generate the 4.4 start manifest and its three seed manifests (22 sections 5 and 8.4).

    python3 scripts/gen_m4_44_manifests.py

ara-m4-4-4-start: the 4.3 start (the 4.2 reference end; 4.3 adds no Agent Builder object that 4.4
carries), plus cortex-file-sar and cortex.file_sar on Tina, ungated.
ara-m4-4-4-seed-<name>: the start plus one seeded extra tool on Tina, from the pool of three.
Tina's entry is restated in full in each, because an agent is applied whole.
"""
import copy
import json
import pathlib

M = pathlib.Path(__file__).resolve().parent.parent / "manifests" / "m4"
end42 = json.loads((M / "ara-m4-4-2-end.json").read_text())
tina = copy.deepcopy(next(a for a in end42["agents"] if a["id"] == "tina-compliance"))


def with_tool(agent: dict, tool_id: str) -> dict:
    a = copy.deepcopy(agent)
    ids = a["configuration"]["tools"][0]["tool_ids"]
    if tool_id not in ids:
        ids.append(tool_id)
    return a


def wf_tool(tool_id: str, workflow_id: str, description: str) -> dict:
    return {"id": tool_id, "type": "workflow", "tags": ["cortex"], "description": description,
            "configuration": {"workflow_id": workflow_id}}


tina44 = with_tool(tina, "cortex.file_sar")
start = {
    "id": "ara-m4-4-4-start",
    "_doc": "The 4.4 start state (22 sections 5 and 8.4): the 4.3 start (the 4.2 reference end), plus cortex-file-sar and "
            "cortex.file_sar on Tina, ungated. The 4.3 learner key and .mcp.json are not carried. One seeded extra tool is "
            "added by one of the ara-m4-4-4-seed-* manifests, which extend this one. Generated by scripts/gen_m4_44_manifests.py.",
    "extends": "ara-m4-4-3-start",
    "workflows": [{"id": "cortex-file-sar", "yaml_file": "workflows/cortex-file-sar.yml"}],
    "tools": [wf_tool("cortex.file_sar", "cortex-file-sar",
                      "Files a suspicious activity report (SAR) for a Cortex account with the regulator through the "
                      "cortex-file-sar workflow, and records the filing in cortex-sar-filings with status transmitted. "
                      "Cortex rule: a transmitted SAR cannot be withdrawn.")],
    "agents": [tina44],
}
(M / "ara-m4-4-4-start.json").write_text(json.dumps(start, indent=1) + "\n")

SEEDS = [
    ("flag-for-review", "cortex.flag_for_review", "cortex-flag-for-review",
     "Flags a Cortex account for a second analyst's review: writes an open flag document to cortex-review-flags through "
     "the cortex-flag-for-review workflow. A flag can be closed or removed later."),
    ("freeze-account", "cortex.freeze_account", "cortex-freeze-account",
     "Places a hold on a Cortex account: writes the account's hold record to cortex-account-holds through the "
     "cortex-freeze-account workflow. Lifting the hold updates or removes that record."),
    ("share-with-partner-bank", "cortex.share_with_partner_bank", "cortex-share-with-partner-bank",
     "Sends a Cortex case's findings to the correspondent partner bank's fraud desk over HTTPS through the "
     "cortex-share-with-partner-bank workflow, outside Cortex."),
]
for name, tid, wid, desc in SEEDS:
    seed = {
        "id": f"ara-m4-4-4-seed-{name}",
        "_doc": f"4.4 seeded extra tool (22 section 5 start state): {tid} on Tina. Extends ara-m4-4-4-start. "
                "Generated by scripts/gen_m4_44_manifests.py.",
        "extends": "ara-m4-4-4-start",
        "workflows": [{"id": wid, "yaml_file": f"workflows/{wid}.yml"}],
        "tools": [wf_tool(tid, wid, desc)],
        "agents": [with_tool(tina44, tid)],
    }
    (M / f"ara-m4-4-4-seed-{name}.json").write_text(json.dumps(seed, indent=1) + "\n")
print("wrote ara-m4-4-4-start.json and 3 seed manifests")
